#!/usr/bin/env python3
"""Builds assets/search-index.js, the search index used by the search box of every page.

Run it from anywhere after changing the text of a page:

    python3 scripts/build-search-index.py

The index is a JavaScript file (not JSON) so that search also works when the
pages are opened directly from disk, where browsers refuse to fetch files.
Only the Python standard library is needed.
"""
import json
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "assets" / "search-index.js"
MAX_TEXT = 1500
SKIP_TAGS = {"script", "style", "nav", "button", "noscript"}
# Folders that are not part of the site: tool folders, the local notes, the working copies of a coding agent
# and the pages that the deployment collects.
SKIP_NAMES = {".git", "node_modules", "handoff", ".claude", "_site"}


def course_pages():
    """Pages of the course site, home first, then in path order. The archived lessons and the lab sheets are left out."""
    pages = [ROOT / "index.html"]
    for path in sorted(ROOT.rglob("*.html")):
        relative = path.relative_to(ROOT).as_posix()
        if any(part in SKIP_NAMES for part in path.relative_to(ROOT).parts):
            continue
        if path == ROOT / "index.html" or relative.startswith(("archive/lessons/", "archive/reference/")):
            continue
        if path.name == "lab-sheet.html":
            # A lab sheet repeats a part of its chapter page.
            continue
        pages.append(path)
    return pages


class SectionParser(HTMLParser):
    """Splits the main content of a page into sections that start at each h1, h2 or h3."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.in_main = False
        self.skip_depth = 0
        self.heading = None
        self.heading_text = []
        self.sections = []

    def handle_starttag(self, tag, attrs):
        if tag == "main":
            self.in_main = True
            return
        if not self.in_main:
            return
        if tag in SKIP_TAGS:
            self.skip_depth += 1
            return
        if tag in {"h1", "h2", "h3"} and not self.skip_depth:
            self.heading = (tag, dict(attrs).get("id", ""))
            self.heading_text = []
        if tag in {"p", "li", "td", "th", "pre", "summary", "br", "h4", "figcaption"}:
            self._text(" ")

    def handle_endtag(self, tag):
        if tag == "main":
            self.in_main = False
            return
        if not self.in_main:
            return
        if tag in SKIP_TAGS and self.skip_depth:
            self.skip_depth -= 1
            return
        if self.heading and tag == self.heading[0]:
            title = " ".join("".join(self.heading_text).split())
            self.sections.append({"level": tag, "id": self.heading[1], "title": title, "text": []})
            self.heading = None

    def handle_data(self, data):
        if not self.in_main or self.skip_depth:
            return
        if self.heading:
            self.heading_text.append(data)
        else:
            self._text(data)

    def _text(self, data):
        if self.sections:
            self.sections[-1]["text"].append(data)


def build_index():
    entries = []
    for path in course_pages():
        parser = SectionParser()
        parser.feed(path.read_text(encoding="utf-8"))
        relative = path.relative_to(ROOT).as_posix()
        page_title = next((s["title"] for s in parser.sections if s["level"] == "h1"), relative)
        for section in parser.sections:
            text = " ".join("".join(section["text"]).split())[:MAX_TEXT]
            url = relative if section["level"] == "h1" or not section["id"] else f"{relative}#{section['id']}"
            entries.append({"page": page_title, "title": section["title"], "url": url, "text": text})
    return entries


def render(entries):
    body = json.dumps(entries, ensure_ascii=False, indent=0)
    return "/* Generated by scripts/build-search-index.py. Do not edit by hand. */\nwindow.COURSE_INDEX = " + body + ";\n"


def main():
    entries = build_index()
    OUTPUT.write_text(render(entries), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} with {len(entries)} sections.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
